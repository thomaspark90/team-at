// 카드대금 이중계상 상쇄 — 전처리1(prepExpense)의 '카드대금 − 수집분' 규칙을 손익 집계
// (지표 aggregate · 관리손익 pnl)에도 적용하기 위한 공용 조각 (2026-08-20 진단).
//
// 스탭밀 카드대금 인출(비씨선결제·BC바로·현대)은 명세가 없어 '재료비'로 분류돼 손익에 들어가고,
// 같은 카드로 결제된 네이버페이·쿠팡 세부 수집분도 각자 계정으로 분류돼 또 들어간다 —
// 그대로 합치면 같은 돈이 두 번 잡혀 월 600만~1,200만원씩 지출이 부풀었다(2025년 EBIT −1.2억 중
// −0.97억이 이 이중계상). 규칙:
//  - 월 단위에서만 차감한다(전처리1과 동일 — 일·주는 결제일/사용일이 어긋나 같은 칸에서 못 뺀다).
//  - 손익에 실제로 실린 카드대금과 수집분 중 작은 쪽만큼만 뺀다(clamp).
//    카드대금이 0인 달(은행 자료 미업로드·명세 대사 완료)은 차감 0 — 수집분이 유일한 지출 자료로 남는다.
//  - 카드 명세를 올려 인출이 '카드대금정산'으로 대사되면 그 인출은 손익에서 빠지므로 이 상쇄도
//    자연히 0이 된다(그때는 명세 행 ↔ 수집분 중복이 새 과제 — 전처리1도 동일한 미해결 지점).

/**
 * 통장에서 카드사로 나가는 결제 대금의 기재내용 패턴. 스탭밀 실제 기재는
 * '비씨카드선결제' · 'BC바로카드' · '현대카드' 세 가지(2026-08-19 원본 확인).
 * 카드사가 늘면 여기에 추가한다 — 놓치면 카드대금이 은행 직접지출로 새어 들어간다.
 * ⚠️ finance.dashboard_tx 뷰의 is_card_payment 계산식(SQL 정규식)과 반드시 동일하게 유지할 것.
 */
export const CARD_PAYMENT_RE =
  /(비씨카드|BC바로카드|BC카드|현대카드|신한카드|삼성카드|국민카드|롯데카드|하나카드|우리카드)/;

/** 자동수집 소스 — 결제가 사실상 전량 카드라 카드대금 인출과 겹친다 */
export const COLLECTED_SOURCES = new Set(['naverpay', 'coupang']);

/** 손익에 같이 실린 카드대금·수집분에서 겹치는 몫 — 음수 방지 클램프 */
export const cardDupOffset = (cardPay: number, collected: number) =>
  Math.max(0, Math.min(cardPay, collected));
