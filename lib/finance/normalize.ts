// 자동분류·학습용 정규화 키.
// 은행 memo는 매달 날짜·번호 꼬리가 바뀌므로(토스_2026070 → 토스_2026062,
// 최은숙 6/28 → 최은숙 6/27) 어근만 남겨야 규칙이 다음 달에도 매칭된다.
//
// 예)
//   '토스_2026070'   → '토스'
//   '현대861456417'  → '현대'
//   '최은숙 6/28'     → '최은숙'
//   '신한모준원 5월'   → '신한모준원'
//   '카카오페이정산'   → '카카오페이정산' (숫자 없음 → 유지)

export function normalizeKey(memo: string): string {
  return memo
    .normalize('NFC')
    // 날짜/기간 표기 먼저 제거 (순서 중요)
    .replace(/\d{4}[.\-]?\d{1,2}[.\-]?\d{1,2}/g, ' ') // 20260701 / 2026.07.01
    .replace(/\d{1,2}\s*\/\s*\d{1,2}/g, ' ') // 6/28
    .replace(/\d{1,2}\s*월(\s*\d{1,2}\s*일)?/g, ' ') // 5월 / 6월 28일
    .replace(/\d{1,2}\s*일/g, ' ') // 28일
    .replace(/\d+/g, ' ') // 나머지 숫자(정산번호 등)
    .replace(/[_\-/()[\]{}.,·]+/g, ' ') // 구분자·특수문자
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}
